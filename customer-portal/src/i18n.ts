export type CopyKey = keyof (typeof copy)["en"];
type Copy = { [K in CopyKey]: string };
const rtl = new Set(["ar", "he", "fa", "ur"]);
const packs: Record<string, Copy> = { ...copy, ...extraCopy, ...extraCopyMore, ...extraCopyRest, ...extraCopyFinal };

export const languages = languageOrder
  .filter((code) => code in packs)
  .map((code) => ({ code, label: languageLabels[code] }));
export type LanguageCode = (typeof languages)[number]["code"];

export function isRtl(language: string) {
  return rtl.has(language);
}

export function text(language: string, key: CopyKey, vars?: Record<string, string | number>) {
  const pack = packs[language] ?? packs.en;
  let value: string = pack[key] ?? packs.en[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

